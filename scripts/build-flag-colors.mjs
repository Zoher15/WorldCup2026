// Generates src/data/flag-colors.ts: the real, area-ordered palette of each
// team's flag, so the brand wave can carry a nation's actual colours (the USA's
// red/white/blue, not one representative hex). Run: node scripts/build-flag-colors.mjs
//
// Reproducible and offline: it reads the flag SVGs that ship with the
// `flag-icons` dependency, rasterizes each with sharp, and clusters the pixels
// into a handful of dominant colours weighted by how much of the flag they cover.
// Re-run after bumping flag-icons or editing the TEAMS table.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import sharp from "sharp";
import { TEAMS } from "../src/lib/fifa.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const flagsDir = join(root, "node_modules/flag-icons/flags/4x3");

// Tuning. The flag is sampled at this size, channels are bucketed to merge
// anti-aliasing noise, near-identical buckets are merged, and only colours
// covering at least MIN_COVERAGE of the flag survive — capped at MAX_COLORS so
// the wave stays a few clean stops, not a noisy gradient of every emblem tint.
const SAMPLE_W = 160;
const SAMPLE_H = 120;
const BUCKET = 16; // channel quantization step
const MERGE_DIST = 34; // RGB distance under which two clusters are one colour
const MIN_COVERAGE = 0.08;
const MAX_COLORS = 3;

const hex = (r, g, b) =>
  "#" + [r, g, b].map((c) => Math.round(c).toString(16).padStart(2, "0")).join("");
const dist = (a, b) => Math.hypot(a.r - b.r, a.g - b.g, a.b - b.b);

/** The dominant flag colours for an ISO code as `[hex, weight]` pairs, ordered
 *  by how much area they cover (most first); weights are the kept colours'
 *  coverage renormalized to sum to 1, so the wave can size each colour's band to
 *  its real share of the flag. */
async function paletteFor(iso) {
  const svg = readFileSync(join(flagsDir, `${iso}.svg`));
  const { data, info } = await sharp(svg)
    .resize(SAMPLE_W, SAMPLE_H, { fit: "fill" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  // Bucket pixels, accumulating the true colour sum per bucket so each cluster
  // reports its average rather than the quantized corner.
  const buckets = new Map();
  let total = 0;
  for (let i = 0; i < data.length; i += info.channels) {
    const [r, g, b, a] = [data[i], data[i + 1], data[i + 2], data[i + 3]];
    if (a < 128) continue; // skip transparent pixels (shouldn't occur on flags)
    total++;
    const key =
      Math.round(r / BUCKET) * 10_000 +
      Math.round(g / BUCKET) * 100 +
      Math.round(b / BUCKET);
    const acc = buckets.get(key) ?? { r: 0, g: 0, b: 0, n: 0 };
    acc.r += r;
    acc.g += g;
    acc.b += b;
    acc.n++;
    buckets.set(key, acc);
  }

  // Heaviest buckets first, merging any that sit within MERGE_DIST of an already
  // kept cluster (so a flag's anti-aliased reds collapse to one red).
  const sorted = [...buckets.values()]
    .map((c) => ({ r: c.r / c.n, g: c.g / c.n, b: c.b / c.n, n: c.n }))
    .sort((a, b) => b.n - a.n);
  const clusters = [];
  for (const c of sorted) {
    const near = clusters.find((k) => dist(k, c) < MERGE_DIST);
    if (near) {
      const n = near.n + c.n;
      near.r = (near.r * near.n + c.r * c.n) / n;
      near.g = (near.g * near.n + c.g * c.n) / n;
      near.b = (near.b * near.n + c.b * c.n) / n;
      near.n = n;
    } else {
      clusters.push({ ...c });
    }
  }

  const kept = clusters
    .filter((c) => c.n / total >= MIN_COVERAGE)
    .slice(0, MAX_COLORS);
  const keptTotal = kept.reduce((s, c) => s + c.n, 0);
  return kept.map((c) => [hex(c.r, c.g, c.b), c.n / keptTotal]);
}

const entries = [];
for (const [code, info] of Object.entries(TEAMS)) {
  const palette = await paletteFor(info.iso);
  if (palette.length === 0) throw new Error(`no palette extracted for ${code}`);
  entries.push([code, palette]);
}

const body = entries
  .map(
    ([code, palette]) =>
      `  ${code}: [${palette
        .map(([c, w]) => `["${c}", ${w.toFixed(3)}]`)
        .join(", ")}],`,
  )
  .join("\n");

const out = `// AUTO-GENERATED by scripts/build-flag-colors.mjs — do not edit by hand.
// Each team's dominant flag colours as [hex, weight] pairs, ordered by how much
// of the flag they cover (most first); the weights sum to 1. Used by the brand
// wave (src/lib/wave-colors.ts) so a matchup carries the nations' real colours,
// each sized to its share of the flag. Regenerate after a flag-icons bump.

/** FIFA code -> the flag's dominant colours as [\`#rrggbb\`, areaShare], most
 *  prominent first; the shares sum to 1. */
export const FLAG_COLORS: Record<string, [string, number][]> = {
${body}
};
`;

writeFileSync(join(root, "src/data/flag-colors.ts"), out);
console.log(`Wrote src/data/flag-colors.ts (${entries.length} teams).`);
