// Generates src/data/fixtures.ts and supabase/seed.sql from the committed
// openfootball 2026 schedule snapshot. Run: node scripts/build-fixtures.mjs
//
// Reproducible and offline: it reads scripts/openfootball-2026.json. To refresh
// the schedule, re-download that file from
// https://raw.githubusercontent.com/openfootball/worldcup.json/master/2026/worldcup.json
// and re-run this script.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { NAME_TO_CODE } from "../src/lib/fifa.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const src = JSON.parse(
  readFileSync(join(here, "openfootball-2026.json"), "utf8"),
);

const STAGE_BY_ROUND = {
  "Round of 32": "round_of_32",
  "Round of 16": "round_of_16",
  "Quarter-final": "quarter_final",
  "Semi-final": "semi_final",
  "Match for third place": "third_place",
  Final: "final",
};

// "13:00 UTC-6" + "2026-06-11" -> UTC ISO string.
function toUtcIso(date, time) {
  const match = /^(\d{2}):(\d{2})\s+UTC([+-]\d{1,2})$/.exec(time);
  if (!match) throw new Error(`unparseable time: ${time}`);
  const [, hh, mm, off] = match;
  const sign = off[0];
  const offH = String(Math.abs(parseInt(off, 10))).padStart(2, "0");
  const iso = `${date}T${hh}:${mm}:00${sign}${offH}:00`;
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) throw new Error(`bad date: ${iso}`);
  return d.toISOString();
}

// Turn a knockout placeholder token into a readable label.
function placeholderLabel(token) {
  if (/^[12][A-L]$/.test(token)) {
    const rank = token[0] === "1" ? "Winner" : "Runner-up";
    return `${rank} Group ${token[1]}`;
  }
  if (/^3/.test(token)) return `3rd place ${token.slice(1)}`;
  let m;
  if ((m = /^W(\d+)$/.exec(token))) return `Winner of Match ${m[1]}`;
  if ((m = /^L(\d+)$/.exec(token))) return `Loser of Match ${m[1]}`;
  return token;
}

function teamFields(name) {
  const code = NAME_TO_CODE[name] ?? null;
  if (code) return { code, label: null };
  return { code: null, label: placeholderLabel(name) };
}

const rows = src.matches.map((m) => {
  const stage = m.group ? "group" : STAGE_BY_ROUND[m.round];
  if (!stage) throw new Error(`unknown round: ${m.round}`);
  const home = teamFields(m.team1);
  const away = teamFields(m.team2);
  return {
    stage,
    groupLabel: m.group ? m.group.replace(/^Group\s+/, "") : null,
    homeCode: home.code,
    awayCode: away.code,
    homeLabel: home.label,
    awayLabel: away.label,
    kickoffAt: toUtcIso(m.date, m.time),
    venue: m.ground,
  };
});

// Assign match numbers by chronological kickoff (stable for simultaneous games).
rows.sort((a, b) =>
  a.kickoffAt < b.kickoffAt ? -1 : a.kickoffAt > b.kickoffAt ? 1 : 0,
);
rows.forEach((r, i) => (r.matchNumber = i + 1));

// --- emit src/data/fixtures.ts ---
const ts = `// AUTO-GENERATED by scripts/build-fixtures.mjs — do not edit by hand.
// Source: openfootball/worldcup.json (2026). Regenerate after schedule changes.

import type { Stage } from "@/lib/types";

export interface Fixture {
  matchNumber: number;
  stage: Stage;
  groupLabel: string | null;
  homeCode: string | null;
  awayCode: string | null;
  homeLabel: string | null;
  awayLabel: string | null;
  kickoffAt: string; // UTC ISO 8601
  venue: string;
}

export const FIXTURES: Fixture[] = ${JSON.stringify(
  rows.map((r) => ({
    matchNumber: r.matchNumber,
    stage: r.stage,
    groupLabel: r.groupLabel,
    homeCode: r.homeCode,
    awayCode: r.awayCode,
    homeLabel: r.homeLabel,
    awayLabel: r.awayLabel,
    kickoffAt: r.kickoffAt,
    venue: r.venue,
  })),
  null,
  2,
)};
`;
writeFileSync(join(root, "src/data/fixtures.ts"), ts);

// --- emit supabase/seed.sql ---
const esc = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const values = rows
  .map(
    (r) =>
      `  (${r.matchNumber}, ${esc(r.stage)}, ${esc(r.groupLabel)}, ${esc(
        r.homeLabel,
      )}, ${esc(r.awayLabel)}, ${esc(r.homeCode)}, ${esc(r.awayCode)}, ${esc(
        r.kickoffAt,
      )}, ${esc(r.venue)})`,
  )
  .join(",\n");
const sql = `-- AUTO-GENERATED by scripts/build-fixtures.mjs — do not edit by hand.
-- Seeds the 104 World Cup 2026 fixtures. Idempotent: re-running updates rows.

insert into matches
  (match_number, stage, group_label, home_team, away_team, home_code, away_code, kickoff_at, venue)
values
${values}
on conflict (match_number) do update set
  stage = excluded.stage,
  group_label = excluded.group_label,
  home_team = excluded.home_team,
  away_team = excluded.away_team,
  home_code = excluded.home_code,
  away_code = excluded.away_code,
  kickoff_at = excluded.kickoff_at,
  venue = excluded.venue;
`;
writeFileSync(join(root, "supabase/seed.sql"), sql);

const groups = rows.filter((r) => r.stage === "group").length;
console.log(
  `Wrote ${rows.length} fixtures (${groups} group, ${rows.length - groups} knockout)`,
);
